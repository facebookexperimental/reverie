    assert!(std::mem::size_of::<ReadySnapshot>() == 48);
    assert!(std::mem::offset_of!(ReadySnapshot, raw_config_digest) == 8);
    assert!(std::mem::offset_of!(ReadySnapshot, owner_generation) == 40);
    assert!(std::mem::size_of::<TerminalFact>() == 104);
    assert!(std::mem::align_of::<TerminalFact>() == 8);
