//! Checked native records for an explicitly selected caller Tool runtime.
//!
//! These records describe native admission, not kernel completion. A successful
//! terminal reservation does not establish that Linux has executed an exit.

/// Leave unselected application CPUID/RDTSC/RDTSCP instructions native.
pub const NATIVE_UNSELECTED_INSTRUCTIONS: u64 = 1;
/// Prepare and consume explicit exits before the native terminal forward.
pub const PREPARED_EXPLICIT_EXIT: u64 = 2;
/// Require acknowledged admission and consuming lifecycle on the primary RPC.
pub const ACKED_CALLER_OWNER: u64 = 4;
/// The complete capability set of the initial single-thread caller domain.
pub const CALLER_CAPABILITIES: u64 =
    NATIVE_UNSELECTED_INSTRUCTIONS | PREPARED_EXPLICIT_EXIT | ACKED_CALLER_OWNER;

/// Immutable image contract, obtained before instruction instrumentation.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ImageDescriptor {
    /// Exact size of this record.
    pub size: u32,
    /// Native callback ABI version.
    pub abi: u32,
    /// Zero for legacy producers, or the complete caller capability set.
    pub capabilities: u64,
    /// Nonzero native image incarnation.
    pub image_generation: u64,
    /// Digest of the declared source/build inputs, not an ELF self-hash.
    pub runtime_input_identity: [u8; 32],
}

impl ImageDescriptor {
    /// Construct the descriptor for a capability-clear legacy producer.
    pub fn legacy(image_generation: u64) -> Self {
        Self {
            size: std::mem::size_of::<Self>() as u32,
            abi: crate::DBT_RUNTIME_ABI_VERSION,
            image_generation,
            ..Self::default()
        }
    }

    /// Validate the finite versioned contract before using any capabilities.
    pub fn is_valid(&self) -> bool {
        self.size as usize == std::mem::size_of::<Self>()
            && self.abi == crate::DBT_RUNTIME_ABI_VERSION
            && self.image_generation != 0
            && matches!(self.capabilities, 0 | CALLER_CAPABILITIES)
    }
}

/// Snapshot written only after a typed configuration owner was published.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ReadySnapshot {
    /// Exact size of this record.
    pub size: u32,
    /// Selected instruction bits: CPUID at bit zero, RDTSC at bit one.
    pub selected_event_bits: u32,
    /// Digest of the actual received Config frame before decoding.
    pub raw_config_digest: [u8; 32],
    /// Image generation whose immutable owner is ready.
    pub owner_generation: u64,
}

/// Reservation made by the actual native application callback.
///
/// `kind == 1` is an admitted explicit exit; `kind == 2` records an unobserved
/// terminal notification and supplies no status. Neither means kernel success.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct TerminalFact {
    /// Exact size of this record.
    pub size: u32,
    /// One for explicit exit, two for an unobserved notification.
    pub kind: u32,
    /// Native image generation.
    pub image: u64,
    /// Actual native callback context.
    pub context: u64,
    /// Actual application process ID.
    pub pid: i32,
    /// Actual application thread ID.
    pub tid: i32,
    /// Final native syscall number, never a Tool's original discarded request.
    pub sysno: i64,
    /// Exact six final syscall operands.
    pub args: [u64; 6],
    /// Nonzero reservation cookie generated by native admission.
    pub cookie: u64,
    /// One for original forwarding, two for deferred Tool forwarding.
    pub origin: u32,
    /// Must be zero.
    pub reserved: u32,
}

impl TerminalFact {
    /// Validate an explicit reservation against its live application owner.
    pub fn matches_owner(&self, context: usize, pid: i32, tid: i32, image: u64) -> bool {
        self.size as usize == std::mem::size_of::<Self>()
            && self.kind == 1
            && self.context == context as u64
            && self.pid == pid
            && self.tid == tid
            && pid > 0
            && tid > 0
            && self.image == image
            && image != 0
            && self.cookie != 0
            && matches!(self.sysno, libc::SYS_exit | libc::SYS_exit_group)
            && matches!(self.origin, 1 | 2)
            && self.reserved == 0
    }
}

/// Reserve an explicit terminal action without taking Tool or thread state.
/// Returns one after writing the complete reservation, nonpositive on refusal.
pub type TerminalAdmission = unsafe extern "C" fn(usize, i64, *const u64, *mut TerminalFact) -> i32;

